import { test, expect } from '@playwright/test';
import { randomUUID } from 'node:crypto';
import { registerCell } from './helpers/cells';

for (const width of [390, 1440]) {
 test(`admin manages tenant settings and cell hook inheritance at ${width}px`, async ({ page, request, context, baseURL }) => {
  const tenant = `admin-${randomUUID()}`;
  const cell = await registerCell(request, tenant);
  await context.addCookies([{ name: 'colony2:user:email', value: 'browser@example.com', url: baseURL! }]);
  await page.setViewportSize({ width, height: 844 });
  await page.goto(`/project/${tenant}/cells`);
  if (width < 768) await page.getByRole('button', { name: 'Open navigation' }).click();
  await page.getByRole('link', { name: 'Admin', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Admin', exact: true })).toBeVisible();
  await page.getByRole('tab', { name: 'Configs', exact: true }).click();
  await page.getByRole('button', { name: 'Add config', exact: true }).click();
  await page.getByLabel('Name', { exact: true }).fill('model');
  await page.getByLabel('Value (JSON)', { exact: true }).fill('"initial"');
  await page.getByRole('button', { name: 'Save', exact: true }).click();
  await expect(page.getByRole('dialog')).not.toBeVisible();
  await page.getByRole('button', { name: 'Edit', exact: true }).click();
  await page.getByLabel('Value (JSON)', { exact: true }).fill('"updated"');
  await page.getByRole('button', { name: 'Save', exact: true }).click();
  await expect(page.getByRole('dialog')).not.toBeVisible();
  await expect(page.getByText('"updated"', { exact: true })).toBeVisible();
  await page.reload();
  await expect(page.getByRole('tab', { name: 'Configs', exact: true })).toHaveAttribute('aria-selected', 'true');
  await expect(page.getByText('"updated"', { exact: true })).toBeVisible();
  await page.getByRole('tab', { name: 'Hook permissions' }).click();
  await page.getByRole('button', { name: 'Add hook policy' }).click();
  await page.getByLabel('Hook path', { exact: true }).fill('.c2/hooks/build.yaml');
  await page.getByLabel('Value (JSON)', { exact: true }).fill(JSON.stringify({ perms: { jobdb: { secrets: { resolve: ['token'] } } }, source_trust: { 'jobdb.secrets.resolve': { token: { mode: 'candidate' } } } }));
  await page.getByRole('button', { name: 'Save', exact: true }).click();
  await expect(page.getByRole('dialog')).not.toBeVisible();
  await expect(page.getByText('.c2/hooks/build.yaml', { exact: true })).toBeVisible();
  await page.goto(`/project/${tenant}/cells/${cell.id}?tab=hooks`);
  await page.getByRole('button', { name: 'Clear permissions' }).click();
  await page.getByRole('button', { name: 'Confirm', exact: true }).click();
  await expect(page.getByText('Cell override', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Use tenant default' }).click();
  await page.getByRole('button', { name: 'Confirm', exact: true }).click();
  await expect(page.getByText('Cell override', { exact: true })).not.toBeVisible();
  await page.getByRole('tab', { name: 'Configs', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Edit', exact: true })).toHaveCount(0);
  await page.getByRole('link', { name: 'Manage configs in Admin' }).click();
  await page.getByRole('tab', { name: 'Git', exact: true }).click();
  await page.getByRole('button', { name: 'Add Git profile' }).click();
  await page.getByLabel('Name', { exact: true }).fill('read');
  await page.getByLabel('Value (JSON)', { exact: true }).fill(JSON.stringify({ version: 1, entries: [{ url: 'https://github.com/acme/', username: 'git', secret_ref: 'git_token' }] }));
  await page.getByRole('button', { name: 'Save', exact: true }).click();
  await expect(page.getByRole('dialog')).not.toBeVisible();
  await expect(page.getByText('read', { exact: true })).toBeVisible();
  await page.getByRole('tab', { name: 'Secrets', exact: true }).click();
  await expect(page.getByText('git_token', { exact: true })).toBeVisible();
  await expect(page.getByText('token', { exact: true })).toBeVisible();
  await expect(page.getByText(/not an inventory or proof/)).toBeVisible();
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true);
  const snap = await (await request.get(`/api/projects/${tenant}/admin`)).json();
  expect(snap.configs).toEqual([{ name: 'model', value: 'updated', source: 'tenant' }]);
  expect(snap.secretReferences).toEqual(['git_token', 'token']);
  expect((await (await request.get(`/api/projects/other-${tenant}/admin`)).json()).configs).toEqual([]);
 });
}
